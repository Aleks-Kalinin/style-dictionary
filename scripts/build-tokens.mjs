/**
 * Builds the design tokens with Style Dictionary.
 *
 *   npm run tokens:build
 *
 * Source of truth:  the tokens/ directory (W3C DTCG format: $value / $type)
 * Outputs:          src/styles/tokens.css        - CSS custom properties
 *                   src/styles/tokens.ts         - the same tokens, for JS
 *
 * Both outputs are generated. Edit the JSON, never the output.
 *
 * Why bother, when plain CSS already worked? Because the CSS was the only
 * copy. Anything else that needs to know the palette — a Storybook docs page,
 * a chart library, a React Native build, a Figma sync — had to re-type it.
 * One source, many targets, no drift.
 */
import StyleDictionary from "style-dictionary";
import { createPropertyFormatter } from "style-dictionary/utils";

const CSS_OUT = "src/styles/";
const BANNER = (extra = "") =>
  `/**\n * DO NOT EDIT - generated by \`npm run tokens:build\`.\n * Source: the tokens/ directory\n${extra} */\n\n`;

/**
 * Names are the token path joined with dashes, with one exception: a trailing
 * `DEFAULT` segment is dropped. JSON cannot let a key be both a leaf and a
 * group, so `--color-accent-solid` and `--color-accent-solid-hover` are
 * authored as `color.accent.solid.DEFAULT` and `color.accent.solid.hover`.
 *
 * The `dark.` prefix is deliberately NOT stripped here. Doing so would give
 * every dark token the same name as its light counterpart, which Style
 * Dictionary reports as a collision. It is removed at format time instead,
 * where the dark values are written under their own selectors.
 */
StyleDictionary.registerTransform({
  name: "name/token-path",
  type: "name",
  transform: (token) => {
    const path =
      token.path.at(-1) === "DEFAULT" ? token.path.slice(0, -1) : token.path;
    return path.join("-");
  },
});

const isDark = (token) => token.path[0] === "dark";
const isPrimitive = (token) => token.filePath.includes("primitive");

/** Section headings, keyed by the source file a token came from. */
const GROUP_LABELS = [
  ["primitive/color", "Neutrals, brand and status ramps"],
  ["primitive/space", "Spacing scale — a 4px base step"],
  ["primitive/typography", "Type scale, weights and families"],
  ["primitive/shape", "Radii and border widths"],
  ["primitive/motion", "Durations and easing"],
  ["primitive/layout", "Layout and z-index layers"],
];

function labelFor(filePath) {
  const normalised = filePath.replace(/\\/g, "/");
  const found = GROUP_LABELS.find(([key]) => normalised.includes(key));
  return found ? found[1] : null;
}

/**
 * Emits the whole themed stylesheet: primitives and the light semantic layer
 * inside `:root`, then the dark overrides twice — once behind the system
 * preference, once behind an explicit `data-theme="dark"`.
 *
 * The duplication is unavoidable in plain CSS (a media query and an attribute
 * selector cannot be combined into one rule), which is exactly the kind of
 * mechanical repetition worth generating rather than maintaining.
 */
StyleDictionary.registerFormat({
  name: "css/themed-variables",
  format: ({ dictionary, options }) => {
    const line = createPropertyFormatter({
      dictionary,
      outputReferences: true,
      format: "css",
      usesDtcg: options.usesDtcg,
    });

    const render = (tokens, indent = "  ") => {
      const out = [];
      let lastFile = null;

      for (const token of tokens) {
        const label = labelFor(token.filePath);
        if (label && token.filePath !== lastFile) {
          out.push(`${indent}/* ${label} */`);
        }
        lastFile = token.filePath;

        // Dark tokens carry a `dark.` prefix in the source to keep their
        // names unique in the dictionary. It is dropped here so they reassign
        // the same custom property as the light value.
        const declaration = line(token).trim().replace(/^--dark-/, "--");
        out.push(indent + declaration);
      }

      return out.join("\n");
    };

    const primitives = dictionary.allTokens.filter(
      (t) => isPrimitive(t) && !isDark(t),
    );
    const semantic = dictionary.allTokens.filter(
      (t) => !isPrimitive(t) && !isDark(t),
    );
    const dark = dictionary.allTokens.filter(isDark);

    return [
      BANNER(` *\n * Two tiers:\n` +
        ` *   PRIMITIVES  raw palette and scales, context-free\n` +
        ` *   SEMANTIC    what a value is *for* — the only tier components may use\n` +
        ` *\n` +
        ` * Only the semantic tier is reassigned for dark mode, which is why no\n` +
        ` * component stylesheet needs to change between themes.\n`),
      ":root {",
      "  /* ---- PRIMITIVES ---- */",
      render(primitives),
      "",
      "  /* ---- SEMANTIC (light) ---- */",
      render(semantic),
      "}",
      "",
      "/* Dark via system preference, unless the user explicitly chose light. */",
      '@media (prefers-color-scheme: dark) {',
      '  :root:not([data-theme="light"]) {',
      render(dark, "    "),
      "  }",
      "}",
      "",
      "/* Dark via the explicit toggle in the header. */",
      ':root[data-theme="dark"] {',
      render(dark),
      "}",
      "",
    ].join("\n");
  },
});

/**
 * A TypeScript view of the same tokens, so code that needs to enumerate them
 * (the Storybook Tokens page, for instance) reads the real list instead of a
 * hand-maintained copy that silently goes stale.
 */
StyleDictionary.registerFormat({
  name: "typescript/token-list",
  format: ({ dictionary, options }) => {
    const entries = dictionary.allTokens
      .filter((t) => !isDark(t))
      .map((token) => {
        const authored = options.usesDtcg
          ? token.original.$value
          : token.original.value;
        const value = String(authored).replace(
          /\{([^}]+)\}/g,
          (_, ref) => `var(--${ref.split(".").join("-")})`,
        );

        return `  { name: "--${token.name}", value: ${JSON.stringify(value)}, type: ${JSON.stringify(
          (options.usesDtcg ? token.$type : token.type) ?? "other",
        )}, tier: "${isPrimitive(token) ? "primitive" : "semantic"}" },`;
      });

    return [
      BANNER(),
      "export interface DesignToken {",
      "  /** The CSS custom property, including the leading dashes. */",
      "  name: string;",
      "  /** The authored value. Semantic tokens keep their var() reference. */",
      "  value: string;",
      "  type: string;",
      '  tier: "primitive" | "semantic";',
      "}",
      "",
      "export const tokens: DesignToken[] = [",
      ...entries,
      "];",
      "",
      "export const tokenNames = tokens.map((token) => token.name);",
      "",
    ].join("\n");
  },
});

const sd = new StyleDictionary({
  source: ["tokens/**/*.json"],
  // Treat $value/$type as the W3C design token format.
  usesDtcg: true,
  platforms: {
    css: {
      // Only the name transform. No value transforms, so every value reaches
      // the stylesheet exactly as authored.
      transforms: ["name/token-path"],
      buildPath: CSS_OUT,
      files: [{ destination: "tokens.css", format: "css/themed-variables" }],
    },
    ts: {
      transforms: ["name/token-path"],
      buildPath: CSS_OUT,
      files: [{ destination: "tokens.ts", format: "typescript/token-list" }],
    },
  },
});

await sd.hasInitialized;
await sd.buildAllPlatforms();
